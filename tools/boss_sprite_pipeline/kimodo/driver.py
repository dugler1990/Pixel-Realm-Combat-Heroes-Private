"""Generate every remaining test cell with the model loaded ONCE.

    driver.py <cells.json> [model]

The CLI reloads an 8B text encoder on every invocation: ~75 s of loading for ~5 s of
generation. 65 cells cost 87 minutes that way, almost all of it reloading the same weights.
This loads once and iterates, so the load is paid a single time.

Two skeletons, and they are not interchangeable:
  model.skeleton is SOMASkeleton30 - 30 joints - and is what the constraint files are built
  against. The model's OUTPUT is already 77 joints, so the BVH export has to be handed
  skeleton.somaskel77. Passing the 30-joint one straight through is what produced
  "einsum(): subscript N has size 77 ... previously seen size 30" on every cell: the failure
  was in this driver's export, not in the model and not in chained prompts.

multi_prompt is True for every call, single prompt or chained, because that is what the CLI
does - the cells generated by the CLI and by this driver sit in the same comparison matrix.

cells.json is a list of {name, prompt, duration, [constraints], [cfg_type], [cfg_weight],
[seed], [steps], [transition], [no_post], [tpose]}.
"""
import json
import os
import sys
import time
import traceback

import torch
from kimodo import load_model
from kimodo.constraints import load_constraints_lst
from kimodo.exports.bvh import save_motion_bvh
from kimodo.skeleton import SOMASkeleton30, global_rots_to_local_rots
from kimodo.tools import seed_everything

CELLS = json.load(open(sys.argv[1]))
MODEL_NAME = sys.argv[2] if len(sys.argv) > 2 else "Kimodo-SOMA-SEED-v1.1"
OUT = "/workspace/runs"
DEV = "cuda:0" if torch.cuda.is_available() else "cpu"

t0 = time.time()
model = load_model(MODEL_NAME, device=DEV)
mskel = model.skeleton                       # 30 joints - constraints, generation
bskel = mskel.somaskel77.to(DEV) if isinstance(mskel, SOMASkeleton30) else mskel   # 77 - export
print("loaded %s in %.0fs  fps=%s  gen=%s export=%s" % (
    MODEL_NAME, time.time() - t0, model.fps, mskel.name, bskel.name), flush=True)

_cons_cache = {}


def constraints_for(path):
    if not path:
        return []
    if path not in _cons_cache:
        _cons_cache[path] = load_constraints_lst(path, mskel)
    return _cons_cache[path]


def texts_and_frames(prompt, duration):
    texts = [t.strip() + "." for t in prompt.split(".") if t.strip()]
    if " " in str(duration).strip():
        ds = [float(x) for x in str(duration).split()]
        assert len(ds) == len(texts), "%d durations vs %d prompts" % (len(ds), len(texts))
    else:
        ds = [float(duration)] * len(texts)
    return texts, [int(d * model.fps) for d in ds]


done = skipped = failed = 0
t_start = time.time()
for i, c in enumerate(CELLS, 1):
    d = os.path.join(OUT, c["name"])
    if os.path.isdir(d) and any(f.endswith(".bvh") for f in os.listdir(d)):
        skipped += 1
        continue
    try:
        texts, nframes = texts_and_frames(c["prompt"], c["duration"])
        seed_everything(int(c.get("seed", 12345)))
        kw = {}
        ct = c.get("cfg_type", "separated")
        if ct != "nocfg":
            kw["cfg_type"] = ct
            w = c.get("cfg_weight", [3.0, 2.0])
            # regular CFG takes ONE float, separated takes two - the CLI unwraps the
            # single-element list for you and calling the model directly does not.
            kw["cfg_weight"] = float(w[0]) if ct == "regular" and isinstance(w, list) else w
        else:
            kw["cfg_type"] = "nocfg"
        out = model(
            texts, nframes,
            constraint_lst=constraints_for(c.get("constraints")),
            num_denoising_steps=int(c.get("steps", 100)),
            num_samples=int(c.get("samples", 2)),
            multi_prompt=True,
            num_transition_frames=int(c.get("transition", 5)),
            post_processing=not c.get("no_post", False),
            return_numpy=True,
            **kw,
        )
        os.makedirs(d, exist_ok=True)
        n = int(out["posed_joints"].shape[0])
        for s in range(n):
            jp = torch.from_numpy(out["posed_joints"][s]).to(DEV)
            jr = torch.from_numpy(out["global_rot_mats"][s]).to(DEV)
            save_motion_bvh(os.path.join(d, "%s_%02d.bvh" % (c["name"], s)),
                            global_rots_to_local_rots(jr, bskel),
                            jp[:, bskel.root_idx, :],
                            skeleton=bskel, fps=model.fps,
                            standard_tpose=bool(c.get("tpose", False)))
        done += 1
        el = time.time() - t_start
        print("[%3d/%3d] OK   %-30s %d clips  %.0fs/cell  eta %.0fmin" % (
            i, len(CELLS), c["name"][:30], n, el / done,
            (len(CELLS) - i) * (el / done) / 60), flush=True)
    except Exception as e:
        failed += 1
        print("[%3d/%3d] FAIL %-30s %s" % (i, len(CELLS), c["name"][:30], str(e)[:110]), flush=True)
        traceback.print_exc()
        sys.stdout.flush()

print("DRIVER_DONE generated=%d skipped=%d failed=%d in %.0fmin" % (
    done, skipped, failed, (time.time() - t_start) / 60), flush=True)
